/**
 * Дария — аварийный «самоуничтожающийся» сервис-воркер.
 *
 * История: прежние версии воркера кэшировали дев-чанки Turbopack (имена
 * без хэшей, код меняется при каждой правке), и браузер пользователя
 * навсегда застревал на старой версии приложения — «похоже откатилось».
 *
 * Этот скрипт ничего НЕ кэширует и ничего НЕ раздаёт (нет fetch-хендлера).
 * Браузер при каждом открытии страницы сверяет /sw.js с установленной
 * версией — этот запрос идёт мимо HTTP-кэша и мимо перехвата старого
 * воркера, так что новая версия гарантированно доезжает. После установки
 * она: выметает все кэши прежних воркеров, снимает собственную регистрацию
 * и перезагружает открытые вкладки. В итоге ни одного воркера не остаётся —
 * страница работает напрямую с сетью и всегда видит свежий код.
 */
self.addEventListener('install', () => {
  self.skipWaiting()
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      // 1. Снести все кэши, оставленные прежними версиями воркера
      try {
        const keys = await caches.keys()
        await Promise.all(keys.map((k) => caches.delete(k)))
      } catch {
        /* чистим что можем */
      }
      // 2. Снять собственную регистрацию — воркеров больше не останется
      try {
        await self.registration.unregister()
      } catch {
        /* не критично */
      }
      // 3. Перезагрузить открытые вкладки, чтобы они взяли свежий код
      try {
        const list = await self.clients.matchAll({ type: 'window', includeUncontrolled: true })
        for (const client of list) {
          if (typeof client.navigate === 'function') {
            client.navigate(client.url).catch(() => {})
          }
        }
      } catch {
        /* вкладки перезагрузит пользователь */
      }
    })()
  )
})
