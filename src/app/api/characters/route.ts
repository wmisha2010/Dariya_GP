async function ensureSeeded() {
  const count = await db.character.count()
  if (count === 0) {
    await db.character.createMany({ data: DEFAULT_CHARACTERS })
    return
  }
  // Обновляем персоны и параметры голоса существующих персонажей,
  // чтобы стили речи применялись без пересоздания базы
  for (const c of DEFAULT_CHARACTERS) {
    await db.character.updateMany({
      where: { slug: c.slug },
      data: {
        persona: c.persona,
        tagline: c.tagline,
        voicePitch: c.voicePitch,
        voiceRate: c.voiceRate,
      },
    })
  }
}

export async function GET() {
  try {
    await ensureSeeded()
    const characters = await db.character.findMany({
      orderBy: { sortOrder: 'asc' },
      select: {
        id: true,
        slug: true,
        name: true,
        emoji: true,
        tagline: true,
        accent: true,
        voicePitch: true,
        voiceRate: true,
        isDefault: true,
      },
    })
    return NextResponse.json({ characters })
  } catch (error) {
    console.error('GET /api/characters error:', error)
    return NextResponse.json({ error: 'Не удалось загрузить персонажей' }, { status: 500 })
  }
}
